"""Per-agent memory: rolling window of round digests + compact running summary.

Digests are generated by code from environment facts, never by an LLM, so
memory is deterministic and contamination-controlled. Pseudonymous identities
(bird names) are assigned by a seeded permutation per run and carry no
treatment information. Memory never crosses runs: the orchestrator constructs
fresh AgentMemory objects for every run.
"""

from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np

PSEUDONYMS = (
    "Kestrel", "Heron", "Plover", "Sparrow", "Swift", "Finch", "Wren", "Tern",
    "Dunlin", "Osprey", "Siskin", "Avocet", "Curlew", "Godwit", "Lapwing", "Merlin",
)


def assign_pseudonyms(n_agents: int, rng: np.random.Generator) -> list[str]:
    if n_agents > len(PSEUDONYMS):
        raise ValueError(f"need at most {len(PSEUDONYMS)} agents, got {n_agents}")
    order = rng.permutation(len(PSEUDONYMS))[:n_agents]
    return [f"Agent {PSEUDONYMS[i]}" for i in order]


@dataclass
class AgentMemory:
    """One agent's within-run memory (window of digests + running counters)."""

    name: str
    window: int = 6
    digests: list[str] = field(default_factory=list)
    rounds_seen: int = 0
    rounds_chaired: int = 0
    own_adopted_count: int = 0
    participation_count: int = 0

    def record_round(
        self,
        round_index: int,
        digest: str,
        was_chair: bool,
        own_adopted: bool,
        participated: bool,
    ) -> None:
        self.rounds_seen += 1
        self.rounds_chaired += int(was_chair)
        self.own_adopted_count += int(own_adopted)
        self.participation_count += int(participated)
        self.digests.append(f"Round {round_index + 1}: {digest}")
        if len(self.digests) > self.window:
            self.digests = self.digests[-self.window :]

    def summary(self) -> str:
        if self.rounds_seen == 0:
            return "This is the first round; there is no history yet."
        return (
            f"Across {self.rounds_seen} completed rounds you spoke up "
            f"{self.participation_count} times, chaired {self.rounds_chaired} rounds, "
            f"and had your own suggestion adopted {self.own_adopted_count} times."
        )

    def render(self) -> str:
        lines = [self.summary()]
        if self.digests:
            lines.append("Recent rounds:")
            lines.extend(self.digests)
        return "\n".join(lines)


def round_digest(
    chair_name: str,
    adopted_author_name: str | None,
    multiplier: float,
    project_value: float,
    payout: float,
    own_balance: float,
    own_participated: bool,
    own_contribution: float,
    public_messages: list[tuple[str, str]],
) -> str:
    """Code-generated factual digest of one round (agent-specific view)."""
    if adopted_author_name is None:
        adoption = "no suggestion was adopted"
    else:
        adoption = f"{adopted_author_name}'s suggestion was adopted"
    me = (
        f"you spoke up and gave {own_contribution:.2f}"
        if own_participated
        else f"you stayed quiet and gave {own_contribution:.2f}"
    )
    msg_part = ""
    if public_messages:
        quoted = "; ".join(f'{who} said "{msg}"' for who, msg in public_messages)
        msg_part = f" Messages: {quoted}."
    return (
        f"{chair_name} chaired; {adoption}; the pooled fund paid {project_value:.2f} "
        f"(rate {multiplier:.2f}), {payout:.2f} to each member; {me}; "
        f"your balance is now {own_balance:.2f}.{msg_part}"
    )
